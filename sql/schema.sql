CREATE TABLE entrevistas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turno INT NOT NULL,
  fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  hora TIME NOT NULL DEFAULT CURRENT_TIME,
  nombre VARCHAR(150) NOT NULL,
  ci VARCHAR(30) NOT NULL,
  telefono VARCHAR(30),
  motivo VARCHAR(50) NOT NULL,
  funcionario VARCHAR(120) NOT NULL,
  area VARCHAR(100),
  observaciones TEXT,
  estado VARCHAR(20) DEFAULT 'En espera',
  creado_en TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_fecha_hora UNIQUE (fecha, hora)
);

CREATE OR REPLACE FUNCTION siguiente_turno()
RETURNS INT LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE nuevo INT;
BEGIN
  SELECT COALESCE(MAX(turno), 0) + 1 INTO nuevo
  FROM entrevistas WHERE fecha = CURRENT_DATE;
  RETURN nuevo;
END;
$$;

CREATE OR REPLACE FUNCTION registrar_entrevista(
  p_nombre VARCHAR, p_ci VARCHAR, p_telefono VARCHAR,
  p_motivo VARCHAR, p_funcionario VARCHAR, p_area VARCHAR,
  p_observaciones TEXT
)
RETURNS TABLE(turno INT, hora TIME)
LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE v_turno INT; v_hora TIME;
BEGIN
  v_hora := CURRENT_TIME;
  v_turno := siguiente_turno();
  INSERT INTO entrevistas
    (turno, fecha, hora, nombre, ci, telefono, motivo,
     funcionario, area, observaciones)
  VALUES
    (v_turno, CURRENT_DATE, v_hora, p_nombre, p_ci, p_telefono,
     p_motivo, p_funcionario, p_area, p_observaciones);
  RETURN QUERY SELECT v_turno, v_hora;
END;
$$;

ALTER TABLE entrevistas ENABLE ROW LEVEL SECURITY;

CREATE POLICY "publico_inserta" ON entrevistas FOR INSERT
TO anon WITH CHECK (true);

CREATE POLICY "admin_lee" ON entrevistas FOR SELECT
TO authenticated USING (true);

CREATE POLICY "admin_actualiza" ON entrevistas FOR UPDATE
TO authenticated USING (true);

CREATE POLICY "admin_borra" ON entrevistas FOR DELETE
TO authenticated USING (true);

GRANT EXECUTE ON FUNCTION registrar_entrevista TO anon;
